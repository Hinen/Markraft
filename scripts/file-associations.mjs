import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { syntaxes } from '../src/files/syntaxRegistry.ts';

// Association support is broader than highlighting support. Do not list
// wildcards or binary extensions: unknown files remain available via Choose an app.
export const plainTextExtensions = ['log', 'conf', 'config', 'text', 'diff', 'patch', 'lst'];
export const associationExtensions = [
  ...new Set([...syntaxes.flatMap((syntax) => syntax.extensions), ...plainTextExtensions]),
].sort();

// macOS ignores CFBundleTypeExtensions whenever LSItemContentTypes is present.
// Tauri only infers a few UTIs from extensions, so those not supplied by macOS
// need imported (not exported) declarations to become Open With candidates.
// These extensions have system UTIs that conform to public.text. All other
// registered extensions get an imported type, including future additions.
export const macOSSystemTextExtensions = [
  'bash',
  'css',
  'csv',
  'diff',
  'htm',
  'html',
  'json',
  'patch',
  'py',
  'sh',
  'svg',
  'text',
  'toml',
  'tsv',
  'txt',
  'xml',
  'yaml',
  'yml',
  'zsh',
];
export const macOSImportedExtensions = associationExtensions.filter(
  (extension) => !macOSSystemTextExtensions.includes(extension),
);
export const macOSImportedType = (extension) => `io.hinen.markraft.imported.${extension}`;

for (const extension of associationExtensions) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(extension))
    throw new Error(`Invalid file association extension: ${extension}`);
}
for (const extension of macOSSystemTextExtensions) {
  if (!associationExtensions.includes(extension))
    throw new Error(`Unregistered macOS system text extension: ${extension}`);
}

const macOSInfoPlist =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n' +
  '<plist version="1.0">\n<dict>\n<key>UTImportedTypeDeclarations</key>\n<array>\n' +
  macOSImportedExtensions
    .map(
      (extension) =>
        '<dict>\n' +
        `<key>UTTypeIdentifier</key><string>${macOSImportedType(extension)}</string>\n` +
        '<key>UTTypeConformsTo</key><array><string>public.text</string></array>\n' +
        '<key>UTTypeTagSpecification</key><dict>' +
        `<key>public.filename-extension</key><array><string>${extension}</string></array>` +
        '</dict>\n</dict>\n',
    )
    .join('') +
  '</array>\n</dict>\n</plist>\n';

const generated =
  '; Generated by npm run associations. Do not edit.\n' +
  ['REGISTER', 'UNREGISTER']
    .map(
      (action) =>
        `!macro MARKRAFT_${action}_ALL_EXTENSIONS\n` +
        associationExtensions
          .map((extension) => `  !insertmacro MARKRAFT_${action}_EXTENSION "${extension}"`)
          .join('\n') +
        '\n!macroend\n',
    )
    .join('\n');

const root = new URL('../', import.meta.url);
const configPath = new URL('src-tauri/tauri.conf.json', root);
const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
config.bundle.fileAssociations = [
  {
    ext: associationExtensions,
    name: 'Markraft.Document',
    role: 'Editor',
    rank: 'Alternate',
    contentTypes: [
      'public.text',
      // macOS uses video UTIs for .ts and .mts even when they contain TypeScript.
      'public.mpeg-2-transport-stream',
      'public.avchd-mpeg-2-transport-stream',
      ...macOSImportedExtensions.map(macOSImportedType),
    ],
  },
];

for (const [path, content] of [
  [new URL('src-tauri/windows/associations.generated.nsh', root), generated],
  [new URL('src-tauri/Info.plist', root), macOSInfoPlist],
  [configPath, JSON.stringify(config, null, 2) + '\n'],
]) {
  const current = fs.existsSync(path) ? fs.readFileSync(path, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current === content) continue;
  if (process.argv.includes('--check'))
    throw new Error(`Stale associations: ${fileURLToPath(path)}. Run npm run associations.`);
  fs.writeFileSync(path, content);
}
console.log(
  `File associations: ${associationExtensions.length} extensions (${process.argv.includes('--check') ? 'checked' : 'generated'}).`,
);
